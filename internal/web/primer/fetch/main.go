// Command fetch writes internal/web/static/css/primer.css from Primer's
// published design tokens (see package primer for what that is and why):
//
//	go run ./internal/web/primer/fetch
//
// It reads css/tokens.css to learn which Primer names the page uses, downloads
// the pinned version's theme and base files, keeps those names and whatever
// they are defined in terms of, and writes the result. Run it from the
// repository root after changing primer.Version or the names in tokens.css,
// and read the diff. It is the only thing here that goes online.
package main

import (
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/ZachCurry13/isoshelf/internal/web/primer"
)

func main() {
	css := filepath.Join("internal", "web", "static", "css")
	tokens, err := os.ReadFile(filepath.Join(css, "tokens.css"))
	if err != nil {
		fail("run this from the repository root: %v", err)
	}
	wanted := primer.Wanted(string(tokens))
	client := &http.Client{Timeout: 30 * time.Second}

	base := map[primer.File]*primer.Block{}
	var baseBlocks []*primer.Block
	for _, f := range primer.Base {
		b := parse(client, f)
		base[f] = b
		baseBlocks = append(baseBlocks, b)
	}
	themes := map[string]*primer.Block{}
	var themeBlocks []*primer.Block
	for _, t := range primer.Themes {
		b := parse(client, t.File)
		themes[t.Name] = b
		themeBlocks = append(themeBlocks, b)
	}
	// Everything wanted, plus what those are defined in terms of.
	keep := primer.Close(wanted, append(baseBlocks, themeBlocks...)...)

	var out strings.Builder
	fmt.Fprintf(&out, `/* GENERATED by "go run ./internal/web/primer/fetch" - do not edit.
   Design tokens from @primer/primitives %s (MIT, https://github.com/primer/primitives),
   keeping only the names css/tokens.css uses and what they are defined in
   terms of. They are Primer's names, so primer.style/product/primitives
   describes them as written. To change the version, change primer.Version and
   run the command. */
`, primer.Version)
	for _, f := range primer.Base {
		fmt.Fprintf(&out, "\n/* %s */\n%s", f, primer.Filter(base[f], keep))
	}
	for _, t := range primer.Themes {
		fmt.Fprintf(&out, "\n/* theme %s (%s) */\n%s", t.Name, t.File, primer.Filter(themes[t.Name], keep))
	}
	path := filepath.Join(css, "primer.css")
	if err := os.WriteFile(path, []byte(out.String()), 0o644); err != nil {
		fail("%v", err)
	}
	fmt.Printf("wrote %s: %d names from %d used, %d bytes\n", path, len(keep), len(wanted), out.Len())
}

func parse(client *http.Client, f primer.File) *primer.Block {
	resp, err := client.Get(f.URL())
	if err != nil {
		fail("%s: %v", f, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		fail("%s: %s", f.URL(), resp.Status)
	}
	body, err := io.ReadAll(io.LimitReader(resp.Body, 4<<20))
	if err != nil {
		fail("%s: %v", f, err)
	}
	b, err := primer.Parse(string(body))
	if err != nil {
		fail("%s: %v", f, err)
	}
	return b
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
